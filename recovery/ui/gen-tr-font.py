#!/usr/bin/env python3
# Written by Claude 2026-10-10. Generates recovery/ui/font_tr.c: the twelve
# Turkish letters missing from LVGL's built-in Montserrat fonts, rendered from
# the same Montserrat-Medium.ttf that LVGL ships, in LVGL's own font format
# (4 bits per pixel, uncompressed). Each generated font falls back to the
# built-in font of the same size for everything else.
#   gen-tr-font.py LVGL_SOURCE_DIR OUTPUT.c
import re
import sys
from PIL import ImageFont

LETTERS = sorted("ÇÖÜçöüĞğİıŞş", key=ord)
SIZES = (20, 28, 40)

lvgl, out = sys.argv[1], sys.argv[2]
ttf = f"{lvgl}/scripts/built_in_font/Montserrat-Medium.ttf"
first = ord(LETTERS[0])
c = ["/* Generated by gen-tr-font.py from LVGL's Montserrat-Medium.ttf (SIL OFL 1.1). Do not edit. */",
     '#include "lvgl.h"', ""]
for size in SIZES:
    font = ImageFont.truetype(ttf, size)
    builtin = open(f"{lvgl}/src/font/lv_font_montserrat_{size}.c").read()
    metric = lambda name: int(re.search(rf"\.{name} = (\d+)", builtin).group(1))
    bitmap, glyphs = [], ["{0}"]
    for ch in LETTERS:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        mask = font.getmask(ch)
        w, h = mask.size
        assert (w, h) == (x1 - x0, y1 - y0), (ch, size)
        nibbles = [mask.getpixel((x, y)) >> 4 for y in range(h) for x in range(w)]
        if len(nibbles) % 2:
            nibbles.append(0)
        glyphs.append("{.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}"
                      % (len(bitmap), round(font.getlength(ch) * 16), w, h, x0, -y1))
        bitmap += [nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2)]
    n = size
    c += [f"static const uint8_t bitmap_{n}[] = {{" + ",".join(map(str, bitmap)) + "};",
          f"static const lv_font_fmt_txt_glyph_dsc_t glyphs_{n}[] = {{\n\t" + ",\n\t".join(glyphs) + "\n};",
          f"static const uint16_t list_{n}[] = {{" + ",".join(str(ord(ch) - first) for ch in LETTERS) + "};",
          f"static const lv_font_fmt_txt_cmap_t cmap_{n}[] = {{{{",
          f"\t.range_start = {first}, .range_length = {ord(LETTERS[-1]) - first + 1}, .glyph_id_start = 1,",
          f"\t.unicode_list = list_{n}, .glyph_id_ofs_list = NULL, .list_length = {len(LETTERS)},",
          "\t.type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,", "}};",
          f"static const lv_font_fmt_txt_dsc_t dsc_{n} = {{",
          f"\t.glyph_bitmap = bitmap_{n}, .glyph_dsc = glyphs_{n}, .cmaps = cmap_{n},",
          "\t.cmap_num = 1, .bpp = 4, .bitmap_format = LV_FONT_FMT_TXT_PLAIN,", "};",
          f"const lv_font_t font_tr_{n} = {{",
          "\t.get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
          f"\t.subpx = LV_FONT_SUBPX_NONE, .underline_position = -1, .underline_thickness = 1, .dsc = &dsc_{n},",
          "\t/* same line metrics as the built-in font, so mixed text sits on one baseline */",
          f"\t.line_height = {metric('line_height')}, .base_line = {metric('base_line')}, .fallback = &lv_font_montserrat_{n},",
          "};", ""]
open(out, "w").write("\n".join(c))
