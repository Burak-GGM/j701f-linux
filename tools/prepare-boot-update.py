#!/usr/bin/env python3
"""Written by Claude 2026-10-08.
Prepare a guarded update of the mainline image in BOOT for the swapped layout
(BOOT = mainline, RECOVERY = vendor 3.18 fallback). Host-only: it writes the
candidate, an Odin tar and phone-side scripts into the output directory. The
generated update.sh must run as root on the phone booted into 3.18 (RECOVERY).
"""
import argparse
import hashlib
import io
import json
from pathlib import Path
import tarfile

ROOT = Path(__file__).resolve().parents[1]
SLOT = ROOT / 'build/kernel/boot-slot.json'
BOOT_BYTES = 33554432

GUARD = '''set -eu
# Generated by tools/prepare-boot-update.py (Claude). Root, vendor 3.18 system only.
[ "$(cat /etc/j701f-system-version)" = BURAK_ALPINE_0_1 ]
[ "$(uname -r)" = 3.18.140-SIMPLE-KERNEL_V1.0 ]
check() { b=/sys/class/block/$1; grep -qx "PARTNAME=$2" "$b/uevent"; [ "$(cat "$b/size")" = "$3" ]; [ "$(cat "$b/dev")" = "$4" ]; [ -b "/dev/$1" ]; }
check mmcblk0p10 BOOT 65536 259:2
check mmcblk0p11 RECOVERY 77824 259:3
[ "$(cat /sys/class/block/mmcblk0/device/type)" = MMC ]
[ "$(cat /sys/class/block/mmcblk0/removable)" = 0 ]
x=$(sha256sum /sys/class/block/mmcblk0/device/cid); [ "${x%% *}" = CID_SHA ]
backup=/home/burak-alpine/j701f/boot-swap/boot-3.18-backup.img
[ "$(wc -c < "$backup")" = 33554432 ]
x=$(sha256sum "$backup"); [ "${x%% *}" = FALLBACK_SHA ]
# The 3.18 fallback must be in RECOVERY before BOOT is touched.
x=$(dd if=/dev/mmcblk0p11 bs=1048576 count=32 2>/dev/null | sha256sum); [ "${x%% *}" = FALLBACK_SHA ]
restore() {
    dd if="$backup" of=/dev/mmcblk0p10 bs=1048576 conv=notrunc 2>/dev/null
    sync
    x=$(sha256sum /dev/mmcblk0p10); [ "${x%% *}" = FALLBACK_SHA ]
    printf 'BOOT_3_18_RESTORE_READBACK_VERIFIED\\n'
}
'''
UPDATE = '''x=$(sha256sum /dev/mmcblk0p10); [ "${x%% *}" = PREVIOUS_SHA ]
image=PHONE_DIR/boot-mainline.img
[ "$(wc -c < "$image")" = IMAGE_BYTES ]
x=$(sha256sum "$image"); [ "${x%% *}" = IMAGE_SHA ]
trap restore EXIT
dd if="$image" of=/dev/mmcblk0p10 bs=1048576 conv=notrunc 2>/dev/null
sync
x=$(sha256sum /dev/mmcblk0p10); [ "${x%% *}" = AFTER_SHA ]
trap - EXIT
printf 'MAINLINE_BOOT_UPDATE_FULL_READBACK_VERIFIED\\n'
'''


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--handoff-dir', type=Path, required=True)
    parser.add_argument('--output-dir', type=Path, required=True)
    parser.add_argument('--phone-dir', required=True, help='e.g. /home/burak-alpine/j701f/boot-update/touch')
    args = parser.parse_args()
    out, handoff = args.output_dir.resolve(), args.handoff_dir.resolve()
    if not all(p.is_relative_to(ROOT / 'build/kernel') for p in (out, handoff)):
        raise ValueError('Paths must be under build/kernel')
    if not args.phone_dir.startswith('/home/burak-alpine/j701f/boot-update/'):
        raise ValueError('Unexpected phone staging path')
    slot = json.loads(SLOT.read_text())
    info = json.loads((handoff / 'container-report.json').read_text())
    candidate = (handoff / 'recovery-mainline-diagnostic.preview.img').read_bytes()
    if sha(candidate) != info['image_sha256']:
        raise ValueError('Stale container')
    guards = json.loads((handoff / 'guard-validation-report.json').read_text())
    if guards['status'] != 'passed':
        raise ValueError('Loader guard validation has not passed for this candidate')
    # Claude 2026-10-10: since the graphical recovery replaced the vendor 3.18
    # system in RECOVERY, images are written by tools/run-recovery-update.sh
    # (the recovery checks the image hash, keeps the previous contents and reads
    # back). That flow needs only the image; the 3.18 scripts and the predicted
    # whole-partition hash below belong to the old flow and need the previous
    # partition image, which is no longer recorded.
    if not slot.get('boot_partition_image'):
        out.mkdir(parents=True, exist_ok=True)
        (out / 'boot-mainline.img').write_bytes(candidate)
        (out / 'manifest.json').write_text(json.dumps(dict(
            status='prepared-for-recovery-update', candidate_sha256=sha(candidate),
            candidate_bytes=len(candidate), handoff_dir=str(handoff.relative_to(ROOT)),
            written=False), indent=2) + '\n')
        print('PASS: image prepared for tools/run-recovery-update.sh; nothing written.')
        return
    fallback = (ROOT / 'build/backups/boot-before-cpu-trial.img').read_bytes()
    if sha(fallback) != slot['fallback_3_18_sha256'] or len(fallback) != BOOT_BYTES:
        raise ValueError('3.18 BOOT backup differs from the recorded fallback')
    # dd conv=notrunc leaves the previous tail in place; rebuild it to predict the hash.
    previous = (ROOT / slot['boot_partition_image']).read_bytes()
    if sha(previous) != slot['boot_partition_sha256'] or len(previous) != BOOT_BYTES:
        raise ValueError('Recorded BOOT partition image is inconsistent')
    after = candidate + previous[len(candidate):]
    out.mkdir(parents=True, exist_ok=True)
    (out / 'boot-mainline.img').write_bytes(candidate)
    (out / 'boot-partition-after.img').write_bytes(after)
    with tarfile.open(out / 'BOOT-mainline.tar', 'w', format=tarfile.USTAR_FORMAT) as tar:
        member = tarfile.TarInfo('boot.img'); member.size = len(candidate); member.mode = 0o644; member.mtime = 0
        tar.addfile(member, io.BytesIO(candidate))
    cid = json.loads((ROOT / 'build/system/manifest.json').read_text())['mmc_cid_sha256']
    guard = GUARD.replace('CID_SHA', cid).replace('FALLBACK_SHA', slot['fallback_3_18_sha256'])
    update = (UPDATE.replace('PREVIOUS_SHA', slot['boot_partition_sha256']).replace('PHONE_DIR', args.phone_dir)
              .replace('IMAGE_BYTES', str(len(candidate))).replace('IMAGE_SHA', sha(candidate))
              .replace('AFTER_SHA', sha(after)))
    (out / 'update.sh').write_text(guard + update)
    (out / 'restore-3.18-to-boot.sh').write_text(guard + 'restore\n')
    (out / 'manifest.json').write_text(json.dumps(dict(
        status='prepared', candidate_sha256=sha(candidate), candidate_bytes=len(candidate),
        previous_boot_partition_sha256=slot['boot_partition_sha256'], after_boot_partition_sha256=sha(after),
        fallback_3_18_sha256=slot['fallback_3_18_sha256'], handoff_dir=str(handoff.relative_to(ROOT)),
        phone_dir=args.phone_dir, written=False), indent=2) + '\n')
    print('PASS: BOOT update prepared; nothing written. After a verified write, update', SLOT.relative_to(ROOT))


if __name__ == '__main__':
    main()
