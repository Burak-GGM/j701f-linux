#!/usr/bin/env python3
# Written by Claude 2026-10-10. Regenerates tools/kmod/s5k3l2-tables.h from the
# vendor's fimc-is-cis-3l2-setB.h (see build/kernel/vendor-camera-reference/SOURCE.txt).
# The conversion itself was first run inline; this file records how.
import pathlib, re
src = pathlib.Path('build/kernel/vendor-camera-reference/sensor/module_framework/cis/fimc-is-cis-3l2-setB.h').read_text()
def arr(name):
    body = re.search(r'%s\[\]\s*=\s*\{(.*?)\};' % name, src, re.S).group(1)
    body = re.sub(r'//[^\n]*', '', re.sub(r'/\*.*?\*/', '', body, flags=re.S))
    return [int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]+|\b\d+\b', body)]
out = ['/* Generated by tools/kmod/gen-s5k3l2-tables.py from the vendor fimc-is-cis-3l2-setB.h',
       ' * (build/kernel/vendor-camera-reference/, Samsung, GPL-2.0). Do not edit. */', '']
def triples(cname, vals):
    out.append('static const struct cam_reg %s[] = {' % cname)
    out.extend('\t{ 0x%04x, 0x%04x, %d },' % tuple(vals[i:i + 3]) for i in range(0, len(vals), 3))
    out.extend(['};', ''])
triples('s5k3l2_initial_reset', arr('sensor_3l2_setfile_B_initial_reset'))
b = arr('sensor_3l2_setfile_B_initial_burst')
out.append('/* written to register 0x6f12, the sensor advancing its own pointer */')
out.append('static const u16 s5k3l2_initial_burst[] = {')
out.extend('\t' + ' '.join('0x%04x,' % v for v in b[i:i + 8]) for i in range(1, len(b), 8))
out.extend(['};', ''])
triples('s5k3l2_initial_other', arr('sensor_3l2_setfile_B_initial_other'))
triples('s5k3l2_mode_2072x1552_30fps', arr('sensor_3l2_setfile_B_2072x1552_30fps'))
pathlib.Path('tools/kmod/s5k3l2-tables.h').write_text('\n'.join(out))

# front sensor (S5K5E3): its mode tables contain the whole initialisation
src = pathlib.Path('build/kernel/vendor-camera-reference/sensor/module_framework/cis/fimc-is-cis-5e3-setB.h').read_text()
out = ['/* Generated by tools/kmod/gen-s5k3l2-tables.py from the vendor fimc-is-cis-5e3-setB.h',
       ' * (build/kernel/vendor-camera-reference/, Samsung, GPL-2.0). Do not edit. */', '']
triples('s5k5e3_mode_1280x960_30fps', arr('sensor_5e3_setfile_B_1280x960_30fps'))
triples('s5k5e3_mode_2576x1932_30fps', arr('sensor_5e3_setfile_B_2576x1932_30fps'))
pathlib.Path('tools/kmod/s5k5e3-tables.h').write_text('\n'.join(out))
